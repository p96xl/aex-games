#!/usr/bin/env python3
"""Generate game/raytab.s (tables for ray.s) and, with --preview, render one frame to PNG using the
SAME fixed-point math as ray.s -- the check that the constants/tables are sane before flashing.

  python3 game/raygen.py                      # -> game/raytab.s
  python3 game/raygen.py --preview out.png [x y angle]   # x,y in tiles, angle 0..1023
"""
import math, struct, sys, zlib
from pathlib import Path

COLS, COLW, SCR_W, SCR_H = 40, 20, 800, 480   # 80x10 was smoother but turns got too slow on the 115200 link
FOV = math.radians(60)
PROJ = (SCR_W / 2) / math.tan(FOV / 2)          # 693 px: wall 1 tile away = PROJ px tall
HK = int(PROJ * 4096)                           # h = HK / perp(Q12)  -> ray.s HK

# '#' stone, 'B' brick, 'E' exit (locked/red until all keys found, then green: walk into it to win),
# 'K' key. Border must be solid (rays never escape).
MAP = """
################
#..#.....#....K#
#..#.##..#.BBB.#
#....#.....B...#
###..#.###.B.###
#....#...#.....#
#.####.#.#####.#
#......#.....#.#
#.BB.#######.#.#
#..B.#K....#...#
#..B...###.#.#.#
##.BBBB..#...#.#
#K.....#.#####.#
#.####.#.....#.#
#......#####...E
################
""".split()
assert len(MAP) == 16 and all(len(r) == 16 for r in MAP)
TILE = {'.': 0, 'K': 0, '#': 1, 'B': 2, 'E': 3}
GRID = [TILE[c] for row in MAP for c in row]
KEYS = [(x, y) for y, row in enumerate(MAP) for x, c in enumerate(row) if c == 'K']
EXIT = next((x, y) for y, row in enumerate(MAP) for x, c in enumerate(row) if c == 'E')
NKEYS = len(KEYS)

BASE = {1: (0x7, 0x9, 0xc), 2: (0xc, 0x5, 0x3), 3: (0x2, 0xf, 0x4), 4: (0xe, 0x1, 0x2)}  # 4 = locked exit
SIDE = (1.0, 0.65)                     # x-face lit, y-face shaded (the classic Wolf3D trick)
FOG = (1.0, 0.75, 0.5, 0.3)            # by distance band, see ray.s
CEIL, FLOOR = "223", "554"

def color(t, side, fog):
    return "".join("%x" % min(15, round(c * SIDE[side] * FOG[fog])) for c in BASE[t])

SIN = [round(16384 * math.sin(2 * math.pi * i / 1024)) for i in range(1024)]
HKEY = HK * 3 // 8                     # key sprite size = 3/8 of a wall at the same depth
# side-view key on a 16x16 grid inside its S x S box: (x0, y0, x1, y1, colour). Hole drawn last.
KSHAPE = [(0, 4, 6, 12, 0), (6, 7, 16, 9, 0), (10, 9, 12, 12, 0), (13, 9, 15, 11, 0), (2, 6, 4, 10, 1)]
KCOL = ("fc2", "640")
OFF = [round(math.atan((c + 0.5 - COLS / 2) / (COLS / 2) * math.tan(FOV / 2)) * 1024 / (2 * math.pi))
       for c in range(COLS)]

def emit_tables(path):
    out = ["/* generated by raygen.py -- do not edit */", "\t.align 2", f"\t.equ HK, {HK}", f"\t.equ COLS, {COLS}", f"\t.equ COLW, {COLW}",
           f"\t.equ HKEY, {HKEY}", f"\t.equ NKEYS, {NKEYS}", f"\t.equ NSHAPE, {len(KSHAPE)}",
           f"\t.equ EXITX, {EXIT[0] * 65536 + 32768}", f"\t.equ EXITY, {EXIT[1] * 65536 + 32768}", "sintab:"]
    out += ["\t.short " + ",".join(map(str, SIN[i:i + 16])) for i in range(0, 1024, 16)]
    out += ["coloff:", "\t.short " + ",".join(map(str, OFF))]
    out += ["colors:"] + [f'\t.asciz "{color(t, s, f)}"' for t in (1, 2, 3, 4) for s in (0, 1) for f in range(4)]
    out += ["keytab:"] + [f"\t.word {x * 65536 + 32768}, {y * 65536 + 32768}" for x, y in KEYS]
    out += ["kshape:"] + [f"\t.byte {a},{b},{c},{d},{e * 4},0,0,0" for a, b, c, d, e in KSHAPE]
    out += [f'c_key:\t.asciz "{KCOL[0]}"', f'c_khole:\t.asciz "{KCOL[1]}"']
    out += [f'c_ceil:\t.asciz "{CEIL}"', f'c_floor:\t.asciz "{FLOOR}"', "maptab:"]
    out += ["\t.byte " + ",".join(map(str, GRID[r * 16:r * 16 + 16])) for r in range(16)]
    Path(path).write_text("\n".join(out) + "\n")

# ---- reference model: line-for-line the integer math in ray.s:render ----
def asr(v, n): return v >> n            # python >> on negatives == arithmetic shift, like AVR32 asr
def cell(x, y): return GRID[(y >> 16) * 16 + (x >> 16)]

def tdiv(a, b): return abs(a) // abs(b) * (1 if (a < 0) == (b < 0) else -1)   # AVR32 divs truncates

def keyview(px, py, pa, kx, ky):
    """ray.s:keyprep -> (depth Q12, left px, size px) or None if behind / too close."""
    dx, dy = asr(kx - px, 4), asr(ky - py, 4)
    c, s = SIN[(pa + 256) & 1023], SIN[pa]
    depth = asr(dx * c + dy * s, 14)
    lat = asr(dy * c - dx * s, 14)
    if depth < 1024: return None
    S = min(HKEY // depth, 400)
    return depth, 400 + tdiv(lat * 693, depth) - (S >> 1), S

def keyrects(left, S):
    """ray.s:kdraw before column clipping -> [(x0, y0, x1, y1, colour)]"""
    top = 240 - (S >> 2)
    return [(left + (a * S >> 4), top + (b * S >> 4), left + (c * S >> 4), top + (d * S >> 4), e)
            for a, b, c, d, e in KSHAPE]

def cast(px, py, pa, c):
    a = (pa + OFF[c]) & 1023
    sx, sy = asr(SIN[(a + 256) & 1023], 3), asr(SIN[a], 3)    # 1/32-tile step
    x, y = px, py
    for _ in range(600):
        x += sx; y += sy
        t = cell(x, y)
        if t: break
    side = 0 if (x >> 16) != ((x - sx) >> 16) else 1
    x -= sx; y -= sy
    for _ in range(5):                                          # bisect toward the wall face
        sx, sy = asr(sx, 1), asr(sy, 1)
        x += sx; y += sy
        if cell(x, y): x -= sx; y -= sy
    perp = asr(asr(x - px, 4) * SIN[(pa + 256) & 1023] + asr(y - py, 4) * SIN[pa], 14)
    perp = max(perp, 64)
    h = min(HK // perp, 480) & ~3
    fog = 0 if perp < 8192 else 1 if perp < 16384 else 2 if perp < 28672 else 3
    return h, (t - 1) * 8 + side * 4 + fog, perp

def preview(path, px=1.5, py=1.5, pa=0):
    pal = [color(t, s, f) for t in (1, 2, 3, 4) for s in (0, 1) for f in range(4)]
    rgb = lambda s: bytes(int(ch, 16) * 17 for ch in s)
    rows = []
    P = int(px * 65536), int(py * 65536)
    cols = [cast(*P, pa, c) for c in range(COLS)]
    img = [[rgb(pal[ci]) if 240 - h // 2 <= yy < 240 - h // 2 + h else rgb(CEIL if yy < 240 else FLOOR)
            for h, ci, _ in cols for _x in range(COLW)] for yy in range(SCR_H)]
    for c, (_, _, perp) in enumerate(cols):          # per column: nearest key in front of the wall
        vis = [v for v in (keyview(*P, pa, *k) for k in [(x * 65536 + 32768, y * 65536 + 32768) for x, y in KEYS]) if v and v[0] < perp
               and v[1] < (c + 1) * COLW and v[1] + v[2] > c * COLW]
        if vis:
            for x0, y0, x1, y1, e in keyrects(*min(vis)[1:]):
                for yy in range(max(y0, 0), min(y1, SCR_H)):
                    for xx in range(max(x0, c * COLW), min(x1, (c + 1) * COLW)):
                        img[yy][xx] = rgb(KCOL[e])
    rows = [b"\0" + b"".join(r) for r in img]
    raw = zlib.compress(b"".join(rows))
    chunk = lambda t, d: struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d))
    Path(path).write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", SCR_W, SCR_H, 8, 2, 0, 0, 0))
                           + chunk(b"IDAT", raw) + chunk(b"IEND", b""))

if __name__ == "__main__":
    # self-check: looking straight at a flat wall, heights must be symmetric and the centre the tallest
    hs = [cast(int(1.5 * 65536), int(1.5 * 65536), 512, c)[0] for c in range(COLS)]   # facing west wall
    assert hs == hs[::-1] and max(hs) == hs[COLS // 2] and hs[COLS // 2] > 0, hs
    # every key and the exit reachable from the start (exit: a free cell next to it)
    seen, todo = {(1, 1)}, [(1, 1)]
    while todo:
        x, y = todo.pop()
        for n in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if GRID[n[1] * 16 + n[0]] == 0 and n not in seen: seen.add(n); todo.append(n)
    ex, ey = EXIT
    assert NKEYS == 3 and all(k in seen for k in KEYS), KEYS
    assert any(n in seen for n in ((ex - 1, ey), (ex, ey - 1), (ex + 1, ey), (ex, ey + 1)))
    # a key dead ahead must draw centred
    v = keyview(1 << 15 | 1 << 16, 1 << 15 | 1 << 16, 0, 3 << 16 | 1 << 15, 1 << 15 | 1 << 16)
    assert v and abs(v[1] + v[2] // 2 - 400) <= 1, v
    if len(sys.argv) > 2 and sys.argv[1] == "--preview":
        a = [float(v) for v in sys.argv[3:6]]
        preview(sys.argv[2], *(a[:2] or [1.5, 1.5]), int(a[2]) if len(a) > 2 else 0)
    else:
        emit_tables(Path(__file__).with_name("raytab.s"))
        print("wrote raytab.s  HK=%d" % HK)
